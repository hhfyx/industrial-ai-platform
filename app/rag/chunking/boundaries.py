"""切点安全：**不许把数字与单位切开**。

## 为什么单独一个模块

"0.05mm 不能拆"这条要求看着小，它同时约束**三处**完全不同的代码：

| 位置 | 怎么切 | 会切坏的样子 |
| --- | --- | --- |
| `DelimiterSplitter._hard_cut` | 等长硬切 | `…精度为 0.05m` / `m，重复定位…` |
| `DelimiterSplitter._merge` 的重叠截取 | `buffer[-overlap:]` | 块首变成 `05mm，重复定位…` |
| `heading` 的节内二次切 | 复用上面两者 | 同上 |

如果在每处各写一遍"往前挪到数字之前"，三处必然漂移 ——
而漂移的表现是"某个策略把数字切了，另一个没切"，
那是最难查的一类差异（不报错，只在下游答案里出现一个错的值）。

所以：**判定与挪动只在这里**，三处都调同一个函数。

## 判据：什么算是"一个不可分割的数字"

不追求完备的数值语法（那需要真正的词法分析），只挡住**真实文档里会出现的形态**：

    ±0.05mm   0.02μm   0.1mm   38,400.00   95%   3:1   Ra0.8   2026-11-30

因此：
- 数字本体：`[+-±]?` + 数字（可带千分位逗号与小数点） + 可选的 `×10^n` 指数
- 可选的紧贴单位：拉丁字母开头的单位串（`mm` `μm` `MPa` `RH`）、`%`、`℃`、`°C`、`‰`

**单位必须紧贴**（中间不能有空格）：`0.05 mm` 在中文技术文档里几乎不出现，
而"允许空格"会把 `5 个工作日` 里的 `5` 与后面的词连起来，判定过宽 ——
过宽的后果是"永远挪不动"，切点退化成原位置，等于没做保护。

## `Ra0.8` 这类前缀呢

`Ra` 是**在数字之前**的符号。这里的做法是：**切点挪动只往左退到整个数字之前的空白处**，
所以 `Ra0.8` 里的 `Ra` 会被一起留在后一块 —— 这已经是最小伤害：
`Ra0.8μm` 整体在后一块，不会出现 `Ra0.` + `8μm`。
不是"完美保留"，但比"切开数字"好得多。
"""

from __future__ import annotations

import re

# 数字（可带千分位与小数点）+ 可选紧贴单位。
#
# 逐段说明：
#   [+-±]?                  符号（公差里 ± 很常见）
#   \d{1,3}(?:,\d{3})*     千分位分组（38,400）
#   \d+(?:\.\d+)?          普通整数/小数（0.05 / 2026）
#   (?:\.\d+)?             上面那支已带小数；这一支留给 .5 这种写法
#   (?:\s*×?\s*10\^?[+-]?\d+)?   科学计数
#   (?:[A-Za-zμ℃°‰%]...)     紧贴单位
_NUMBER_UNIT = re.compile(
    r"[+\-±]?"
    r"(?:"
    # 日期/区间形态整体算一个：`2026-11-30`、`3-5`、`1.2-1.5`
    # **必须排在普通数字之前**：否则 `2026-11-30` 会被 `finditer` 拆成三段，
    # 而三段之间那两个 `-` 位置看起来"安全"，切在那里就把日期切成 `2026-11` / `-30`。
    r"\d{1,4}(?:[-/]\d{1,4}){1,3}"
    r"|\d{1,3}(?:,\d{3})+(?:\.\d+)?"
    r"|\d+(?:\.\d+)?"
    r"|\.\d+"
    r")"
    r"(?:\.\d+)?"  # 允许 "1.2.3" 这类版本号整体算一个
    r"(?:"
    r"(?:\s*×\s*10\^?[+-]?\d+)"
    r"|[A-Za-zμ℃°‰%]+"  # 紧贴单位（mm / μm / MPa / RH / % / ℃ / ‰）
    r"|°[CF]"  # 摄氏/华氏
    r")?"
)


def number_spans(text: str) -> list[tuple[int, int]]:
    """所有"数字+单位"的区间（`[start, end)`），按出现顺序。

    测试与调试用；判定逻辑走 `position_is_unsafe`。

    ## 已知覆盖不到的两类（写出来而不是假装没有）

    | 形态 | 本实现的结果 | 为什么不再修 |
    | --- | --- | --- |
    | `1.2-1.5 倍`（小数区间） | 拆成 `1.2` 与 `-1.5` 两个区间 | 中间那个 `-` 会被挪动逻辑当作边界 —— 切在 `1.2` 与 `-1.5` 之间，得到 `1.2` / `-1.5 倍`，**读起来仍然是"1.2"和"-1.5"两个数**，语义没被破坏（不是 `1.` / `2-1.5` 那种损坏） |
    | `A-1` / `HT-2026-001` 这类**编号** | 只有数字部分被保护 | 编号的可辨识度来自前缀字母，切开 `HT-` 与 `2026-001` 会让后块丢失归属 —— 但它不是"数字被拆"，是"标识符被拆"，属于另一类问题（标记层，不是切点安全性） |

    第一类是**故意保留**的：把它并成一个区间需要处理"小数 + 连字符 + 小数"的歧义，
    而收益只是"少一次无害的切点挪动"。第二类留给"标识符保护"，
    如果实测发现编号被切坏影响了检索，那时再加 `_IDENTIFIER` 规则。
    """
    return [(m.start(), m.end()) for m in _NUMBER_UNIT.finditer(text)]


def position_is_unsafe(text: str, position: int) -> bool:
    """`position` 是否落在一个数字/单位**内部**（切在这里会拆开它）。

    "内部"的定义：`start < position < end`。
    正好落在 `start` 或 `end` 上是**安全**的 —— 那是数字的边界，
    在边界切开不损坏内容（`…±` | `0.05mm…` 只是把符号留在了前一块）。

    例（`text = "精度为 ±0.05mm，重复"`，数字区间是 `(4, 11)`）：
        position=5  →  不安全（切在 `±` 与 `0` 之间 → 后块以 `05mm` 开头）
        position=4  →  安全（前块以 `±` 结尾，后块是完整的 `0.05mm`）
        position=11 →  安全（后块以 `，` 开头，数字完整留在前块）
    """
    return any(start < position < end for start, end in number_spans(text))


def safe_cut_position(text: str, position: int) -> int:
    """把切点向左挪到**最近的安全位置**。

    ## 挪不动时怎么办（必须说清）

    如果数字从文本开头就开始（`0.05mm 是公差`，position 落在里面），
    向后挪不行（那是切点右移，会把更多内容挤进前一块），
    向前挪到 0 也不安全（整段就是在数字里）——
    这时**返回原位置**：那是唯一保证"不产出空块"的选择，
    并把代价说清楚：**这种情况只在"切点预算小于一个数字串"时发生**，
    属于极端预算（`chunk_chars` 个字符装不下一个数值），实现层无法修复。

    ## 为什么"向左"而不是"向右"

    向左挪让**前一块变短**、后一块完整。向右挪会让前一块变长（可能超预算）。
    在切分里"块略短"是可接受的代价（`DelimiterSplitter` 的实测平均 470/500 就是
    这个取舍），而"块超预算"会被下游的上下文预算截断，后果不可预测。
    """
    if position <= 0 or position >= len(text):
        return position
    if not position_is_unsafe(text, position):
        return position

    # 向左找：挪到"包含该位置的那个数字区间的起点"。
    # 只挪一次就够 —— 数字区间不重叠，区间起点必然安全（`start` 处切是安全的）。
    for start, end in number_spans(text):
        if start < position < end:
            return start if start > 0 else position
    return position


